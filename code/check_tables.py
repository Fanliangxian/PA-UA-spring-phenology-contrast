"""Recompute supported tables from packaged derived inputs; label aggregate-only checks."""
from pathlib import Path
import json, os
import numpy as np
import pandas as pd

R=Path(__file__).resolve().parents[1]
O=Path(os.environ.get('PHENOLOGY_OUTPUT',str(R/'reproduced'))).resolve()/'tables'
O.mkdir(parents=True,exist_ok=True)
D=R/'data'
w=pd.read_csv(D/'pair_window_summaries.csv')
s=pd.read_csv(D/'summary/FigS3_support_source_v01.csv')
t1=pd.read_csv(D/'summary/Table1_descriptive_support.csv').set_index('group')
t2=pd.read_csv(D/'summary/Table2_sensitivity_contrasts.csv').set_index('contrast')
checks=[]
def record(target,level,detail):checks.append(dict(target=target,level=level,result='PASS',detail=detail))
def stats(x):
    return dict(zip(['mean','q05','q25','median','q75','q95','min','max'],
                    [float(np.mean(x)),*np.quantile(x,[.05,.25,.5,.75,.95],method='linear').tolist(),float(np.min(x)),float(np.max(x))]))
z=set(s.loc[s.n_strict==0,'pair_id'])
for key,df,col,ncol in [
 ('main_all',w,'mean_full_days','n_full'),
 ('main_complete22',w[w.complete22==1],'mean_full_days','n_full'),
 ('main_incomplete',w[w.complete22==0],'mean_full_days','n_full'),
 ('main_on_strict_roster',w[~w.pair_id.isin(z)],'mean_full_days','n_full'),
 ('main_on_recent_roster',w,'mean_full_days','n_full'),
 ('recent_native',w,'mean_recent_days','n_recent'),
 ('recent_complete22',w[w.complete22==1],'mean_recent_days','n_recent')]:
    values=stats(df[col].to_numpy())
    assert all(np.isclose(v,t1.loc[key,k],rtol=0,atol=1e-12) for k,v in values.items())
    assert len(df)==t1.loc[key,'pairs'] and df[ncol].sum()==t1.loc[key,'pair_years']
    record('Table 1 '+key,'recomputed_from_pair_statistics','Equal pair weights and type-7 quantiles.')
for key,df in [('recent_vs_full',w),('recent_vs_full_complete22',w[w.complete22==1])]:
    v=stats((df.sum_recent_days/df.n_recent-df.sum_full_days/df.n_full).to_numpy())
    assert np.isclose(v['mean'],t2.loc[key,'same_pair_mean_change'],rtol=0,atol=1e-12)
    assert all(np.isclose(v[k],t2.loc[key,'paired_change_'+k],rtol=0,atol=1e-12) for k in ['q05','q25','median','q75','q95'])
    record('Table 2 '+key,'recomputed_from_pair_statistics','Changes are calculated within pairs before summarizing.')
g=json.loads((D/'summary/figure_source_data_v01.json').read_text(encoding='utf-8'))
for key,df,rows in [('Table 1',t1,g['groups']),('Table 2',t2,g['contrasts'])]:
    idkey='group' if key=='Table 1' else 'contrast'
    for row in rows:
        assert all(np.isclose(df.loc[row[idkey],k],v,rtol=0,atol=1e-12) for k,v in row.items() if k!=idkey)
    record(key+' all archived fields','checked_against_archived_aggregates','CSV and independently sealed figure-source JSON agree.')
record('Table 1 strict_native and Table 2 strict_vs_main','aggregate_only','Strict pairwise sums are not supplied; these distributions are not independently recomputed here.')

assert len(s)==18862 and s.pair_id.is_unique and set(s.pair_id)==set(w.pair_id)
assert np.array_equal(s.set_index('pair_id').n_main.sort_index(),w.set_index('pair_id').n_full.sort_index())
counts=pd.DataFrame({'common_years':range(23)})
for name,values in [('main_pairs',s.n_main),('strict_pairs',s.n_strict),('recent_pairs',w.n_recent)]:
    counts[name]=values.value_counts().reindex(range(23),fill_value=0).values
pd.testing.assert_frame_equal(counts,pd.read_csv(D/'summary/support_year_distribution.csv'))
counts.to_csv(O/'Table_S2_support_counts_recomputed.csv',index=False)
record('Table S2','recomputed_from_pair_support_counts','All 18,862 pairs retained in each profile, including five strict-zero pairs.')
zero=s[s.n_strict==0].sort_values('zero_support_label')
pd.testing.assert_frame_equal(zero.reset_index(drop=True),pd.read_csv(D/'summary/FigS3_zero_strict_support_v01.csv').reset_index(drop=True),check_dtype=False)
zero.to_csv(O/'Table_S3_zero_strict_support_recomputed.csv',index=False)
record('Table S3','recomputed_from_pair_support_counts','Identities and coordinates matched against the sealed five-row file.')
annual=pd.read_csv(D/'summary/annual_observed_summary.csv')
assert annual.n_main.sum()==403981 and annual.n_strict.sum()==382773
assert (annual.main_median==-1).all() and (annual.complete22_median==-1).all()
record('Table S1 and Fig S1 annual statistics','aggregate_only','Annual summary CSV reconciles with support totals; annual contrasts are not supplied for recomputation.')

for name in ['Table_S4_direction_and_tolerances.csv','Table_S5_sign_transitions.csv','Table_S6_groups.csv','Table_S7_group_balance.csv','complete_pair_periods.csv']:
    pd.testing.assert_frame_equal(pd.read_csv(O/name),pd.read_csv(D/name),atol=1e-12,rtol=1e-12)
    record(name,'recomputed_from_pair_statistics','Generated by review_descriptives.py and compared with the archived result.')

a=pd.read_csv(D/'spatial/full_18862_spatial_evidence_annotated_v14.csv',float_precision='round_trip')
cnt=a.point_membership.value_counts().to_dict()
assert cnt=={'buffer_only':9753,'outside_frozen_buffered_domain':8807,'inside_original':302}
assert len(a)==18862 and a.pair_id.is_unique and a.partition_id.nunique()==64
assert a.batch_target_disagreement_flag.sum()==5
assert ((a.native_exclusive_ua==1)&(a.native_ua_owner==a.source_city_id)).sum()==18857
assert not set(a.loc[a.batch_target_disagreement_flag==1,'pair_id'])&z
pd.DataFrame([dict(category=k,pairs=v,percent=100*v/18862) for k,v in cnt.items()]).to_csv(O/'Table_S8_point_categories_recomputed.csv',index=False)
record('Tables S8 and S9','reconciled_from_archived_spatial_returns','Three containment counts, 18,857 positive regional records and five discordances retained. No new spatial query or lineage validation.')
pd.DataFrame(checks).to_csv(O/'reproduction_levels.csv',index=False)
(O/'table_checks.json').write_text(json.dumps(dict(checks=checks,all_passed=True),indent=2)+'\n',encoding='utf-8')
print(json.dumps(dict(passed=len(checks),strict_distributions='aggregate_only',annual_distributions='aggregate_only')))
